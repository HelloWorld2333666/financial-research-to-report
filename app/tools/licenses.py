"""Third-party licence report for the Phase 3 app.

    .venv/bin/python app/tools/licenses.py [--write]

Checks every npm package in app/web/package-lock.json, every installed Python distribution, and the
vendored GenOffice subset against an allow-list of permissive licences. Exits non-zero on anything
else. --write regenerates app/THIRD-PARTY-NOTICES.md (including GenOffice's Apache-2.0 NOTICE).
"""

from __future__ import annotations

import importlib.metadata as md
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ALLOWED = {"MIT", "ISC", "BSD-2-Clause", "BSD-3-Clause", "0BSD", "Apache-2.0", "Zlib", "CC-BY-4.0", "PSF-2.0",
           "Python-2.0", "Unlicense", "BlueOak-1.0.0", "MPL-2.0"}
# Dual/compound expressions we accept, with the licence we take
CHOICES = {"(MIT OR GPL-3.0-or-later)": "MIT (chosen)", "(MIT AND Zlib)": "MIT AND Zlib",
           "(Apache-2.0 AND BSD-3-Clause)": "Apache-2.0 AND BSD-3-Clause", "Apache-2.0 OR BSD-3-Clause": "Apache-2.0 (chosen)",
           "BSD-3-Clause OR MIT": "MIT (chosen)", "MIT OR Apache-2.0": "MIT (chosen)", "Apache-2.0 OR MIT": "MIT (chosen)"}
PY_ALIASES = {"MIT License": "MIT", "BSD License": "BSD-3-Clause", "Apache Software License": "Apache-2.0",
              "BSD": "BSD-3-Clause", "Apache 2.0": "Apache-2.0", "Apache License 2.0": "Apache-2.0", "ISC License (ISCL)": "ISC",
              "Python Software Foundation License": "PSF-2.0", "Mozilla Public License 2.0 (MPL 2.0)": "MPL-2.0"}


def ok(lic: str) -> bool:
    if lic in ALLOWED or lic in CHOICES:
        return True
    if re.search(r"\sOR\s", lic):  # dual licence: fine when any alternative is allowed
        return any(ok(p.strip("() ")) for p in re.split(r"\s+OR\s+", lic.strip("()")))
    return all(p.strip("() ") in ALLOWED for p in re.split(r"\s+AND\s+", lic))


def npm_packages():
    lock = json.loads((ROOT / "app/web/package-lock.json").read_text())["packages"]
    for path, p in sorted(lock.items()):
        if path:
            yield path.split("node_modules/")[-1], p.get("version", "?"), p.get("license") or "UNKNOWN", bool(p.get("dev"))


def python_packages():
    for d in sorted(md.distributions(), key=lambda d: (d.metadata["Name"] or "").lower()):
        name = d.metadata["Name"]
        if not name or name == "financial-research-to-report":
            continue
        lic = d.metadata.get("License-Expression") or ""
        if not lic:
            classifiers = [c.split(" :: ")[-1] for c in d.metadata.get_all("Classifier") or [] if c.startswith("License ::")]
            raw = classifiers[0] if classifiers else (d.metadata.get("License") or "UNKNOWN").splitlines()[0][:40]
            lic = PY_ALIASES.get(raw, raw)
        yield name, d.version, lic


def main(write: bool):
    rows, bad = [], []
    for name, ver, lic, dev in npm_packages():
        rows.append(("npm" + (" (dev)" if dev else ""), name, ver, CHOICES.get(lic, lic)))
        if not ok(lic):
            bad.append(f"npm {name}@{ver}: {lic}")
    for name, ver, lic in python_packages():
        rows.append(("python", name, ver, CHOICES.get(lic, lic)))
        if not ok(lic):
            bad.append(f"python {name}=={ver}: {lic}")
    manifest = json.loads((ROOT / "vendor/genoffice/manifest.json").read_text())
    rows.append(("vendored", f"genoffice ({len(manifest['files'])} files)", manifest["commit"][:12], "Apache-2.0"))
    counts: dict[str, int] = {}
    for r in rows:
        counts[r[3]] = counts.get(r[3], 0) + 1
    print(json.dumps(dict(sorted(counts.items(), key=lambda x: -x[1])), indent=1))
    if write:
        notice = ""
        src = ROOT / "vendor/genoffice/src/NOTICE"
        if src.exists():
            notice = src.read_text()
        out = ["# Third-party notices", "", "Generated by `app/tools/licenses.py --write`. Do not edit by hand.", "",
               "## GenOffice (Apache-2.0)", "", f"Vendored subset of genspark-ai/genoffice at `{manifest['commit']}`, fetched by "
               "`vendor/genoffice/tools/sync.py` and modified by the patches in `vendor/genoffice/patches/`. "
               "The `ee/` directory (GenOffice Enterprise License) is never included.", "", "```", notice.strip(), "```", "",
               "## Packages", "", "| Ecosystem | Package | Version | Licence |", "|---|---|---|---|"]
        out += [f"| {a} | {b} | {c} | {d} |" for a, b, c, d in rows]
        (ROOT / "app/THIRD-PARTY-NOTICES.md").write_text("\n".join(out) + "\n")
        print("wrote app/THIRD-PARTY-NOTICES.md")
    if bad:
        print("NOT ALLOWED:\n  " + "\n  ".join(bad))
        sys.exit(1)
    print(f"{len(rows)} entries, all on the allow-list")


if __name__ == "__main__":
    main("--write" in sys.argv)
